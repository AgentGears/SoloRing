# --- Recovery (plan §54, §62-§67) — M3B --------------------------------------


def _stale_cutoff_sql(stale_seconds: int) -> str:
    return db_now_minus_sql(stale_seconds)


async def find_stale_active_generations(
    engine: AsyncEngine, stale_seconds: int
) -> list[dict]:
    """Recovery candidates (plan §62): active, heartbeat stale. Read-only
    scan; the caller (current authority) filters its own worker_id at
    adoption/decision time."""
    from sqlalchemy import text

    cutoff = _stale_cutoff_sql(stale_seconds)
    async with engine.connect() as conn:
        rows = (
            await conn.execute(
                text(
                    "SELECT id, status, worker_id, executor, executor_job_id, "
                    "attempt_id, executor_handle_json, cancel_requested_at "
                    "FROM generations "
                    "WHERE status IN ('preparing','submitted','running','importing') "
                    f"AND heartbeat_at < {cutoff}"
                )
            )
        ).mappings().all()
    return [dict(r) for r in rows]


async def requeue_stale_preparing_generation(
    engine: AsyncEngine, worker_id: str, generation_id: str
) -> OwnershipMutationResult:
    """Requeue a stale preparing Generation (plan §64).

    ONLY safe when no durable executor submission exists — the handle columns
    must be NULL, verified inside the same fenced transaction. queued_at is
    preserved so the request keeps its original queue position; worker
    ownership fields are cleared for the next claim.
    """
    from sqlalchemy import text

    async with _immediate_transaction(engine) as conn:
        lease = (
            await conn.execute(
                text("SELECT worker_id FROM worker_leases WHERE name = :name"),
                {"name": LEASE_NAME},
            )
        ).one_or_none()
        if lease is None or lease.worker_id != worker_id:
            return OwnershipMutationResult.LEASE_LOST

        row = (
            await conn.execute(
                text(
                    "SELECT status, worker_id, attempt_id, executor_job_id, "
                    "executor_handle_json, executor_submission_state "
                    "FROM generations WHERE id = :gid"
                ),
                {"gid": generation_id},
            )
        ).one_or_none()
        if row is None:
            return OwnershipMutationResult.NOT_FOUND
        if row.status != "preparing":
            return OwnershipMutationResult.GENERATION_NOT_ACTIVE
        # M5 amendment §2: requeue is restricted to work with NO modern
        # durable attempt. A non-null attempt_id is never destroyed merely to
        # regain submission permission — such rows are adoption cases.
        if row.attempt_id is not None:
            return OwnershipMutationResult.GENERATION_STATE_CONFLICT
        if row.executor_job_id is not None or row.executor_handle_json is not None:
            # Submission MAY have happened (plan §65 ambiguity): never blindly
            # requeue work that might be running externally.
            return OwnershipMutationResult.GENERATION_NOT_ACTIVE

        await conn.execute(
            text(
                "UPDATE generations SET status = 'queued', worker_id = NULL, "
                "claimed_at = NULL, heartbeat_at = NULL, "
                "executor_submission_state = 'not_started', "
                "submission_possible_at = NULL, "
                f"updated_at = {db_now_sql()} "
                "WHERE id = :gid"
            ),
            {"gid": generation_id},
        )
        return OwnershipMutationResult.OK


async def adopt_stale_generation(
    engine: AsyncEngine, worker_id: str, generation_id: str
) -> OwnershipMutationResult:
    """Adopt a stale active Generation (plan §66): atomic ownership transfer
    to the current authority while verifying the singleton lease."""
    from sqlalchemy import text

    async with _immediate_transaction(engine) as conn:
        lease = (
            await conn.execute(
                text("SELECT worker_id FROM worker_leases WHERE name = :name"),
                {"name": LEASE_NAME},
            )
        ).one_or_none()
        if lease is None or lease.worker_id != worker_id:
            return OwnershipMutationResult.LEASE_LOST

        row = (
            await conn.execute(
                text("SELECT status, worker_id FROM generations WHERE id = :gid"),
                {"gid": generation_id},
            )
        ).one_or_none()
        if row is None:
            return OwnershipMutationResult.NOT_FOUND
        if row.status in TERMINAL_STATUSES:
            return OwnershipMutationResult.GENERATION_NOT_ACTIVE
        if row.worker_id == worker_id:
            return OwnershipMutationResult.OK  # already ours (idempotent)

        await conn.execute(
            text(
                "UPDATE generations SET worker_id = :wid, "
                f"heartbeat_at = {db_now_sql()}, updated_at = {db_now_sql()} "
                "WHERE id = :gid"
            ),
            {"wid": worker_id, "gid": generation_id},
        )
        return OwnershipMutationResult.OK


async def read_cancellation_intent(engine: AsyncEngine, generation_id: str) -> bool:
    """Whether a persisted cancellation request is outstanding (plan §69)."""
    from sqlalchemy import text

    async with engine.connect() as conn:
        val = (
            await conn.execute(
                text(
                    "SELECT cancel_requested_at FROM generations WHERE id = :gid"
                ),
                {"gid": generation_id},
            )
        ).scalar_one_or_none()
    return val is not None


